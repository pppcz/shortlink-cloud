-- =====================================================================
-- 固定窗口计数器限流（原子）。
--
-- KEYS[1] 计数 key
-- ARGV[1] 窗口秒数（首次写入时设置过期）
-- 返回：当前窗口内的计数（1 表示本窗口第 1 次请求）
--
-- 设计说明：
--   * INCR + EXPIRE 放在同一段 Lua 中执行，Redis 单线程保证两步原子，
--     不会出现「INCR 成功但 EXPIRE 没执行」导致 key 永不过期的泄漏。
--   * 只在计数为 1 时设置过期，避免每次请求都刷新 TTL 把窗口无限延长。
--   * 固定窗口在窗口边界理论上允许 2 倍瞬时流量，对本场景（每 IP 每秒几十次）
--     完全够用，且比滑动窗口省一次 ZSET 写入，热路径开销更低。
-- =====================================================================
local current = redis.call('INCR', KEYS[1])
if current == 1 then
    redis.call('EXPIRE', KEYS[1], ARGV[1])
end
return current
